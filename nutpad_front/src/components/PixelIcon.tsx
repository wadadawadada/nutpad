export type IconName = keyof typeof ICONS;

export function PixelIcon({ name, size = 16 }: { name: IconName; size?: number }) {
  const rows = ICONS[name];
  const w = Math.max(...rows.map((r) => r.length));
  return (
    <svg className="pxi" width={(size * w) / rows.length > size ? size : (size * w) / rows.length} height={size} viewBox={`0 0 ${w} ${rows.length}`} shapeRendering="crispEdges" fill="currentColor" aria-hidden="true">
      {rows.flatMap((r, y) => [...r].map((c, x) => (c === '#' ? <rect key={`${x}-${y}`} x={x} y={y} width="1" height="1" /> : null)))}
    </svg>
  );
}
